"""Швидка перевірка, що додаток рендериться без помилок: python scripts/smoke_app.py

"Smoke test" (димовий тест) — найпростіша перевірка "увімкнули — не задимілось":
запускаємо весь app.py без браузера і дивимось, чи не вилетіла помилка.
Він НЕ перевіряє, що цифри правильні — для цього є pytest (tests/).
Потрібні дані в data/raw/ (справжні або з scripts/make_sample_data.py).
"""
# AppTest — вбудований у Streamlit "віртуальний браузер": виконує скрипт додатку
# і дає доступ до всього, що він намалював (вкладки, метрики, таблиці).
from streamlit.testing.v1 import AppTest

# Шлях "../app.py" рахується від папки ЦЬОГО файлу (scripts/), тобто це app.py у корені.
# default_timeout=120 — даємо до 2 хв: перший запуск читає CSV і будує кеш.
# .run() — виконати додаток один раз, як при відкритті сторінки.
at = AppTest.from_file("../app.py", default_timeout=120).run()
# at.exception — список помилок під час виконання. Порожній = все добре.
# assert умова, повідомлення — якщо умова False, програма падає і друкує повідомлення.
assert not at.exception, at.exception
# at.tabs — вкладки, at.metric — великі числа в шапці; друкуємо, щоб на око перевірити, що вони не нульові
print("OK, вкладок:", len(at.tabs), "| метрики:", [m.value for m in at.metric])
